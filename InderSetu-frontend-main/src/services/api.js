const API_BASE_URL = (import.meta.env.VITE_API_BASE_URL || "").replace(/\/$/, "");
let routeBundlePromise;
let environmentLayersPromise;
let seaIceHeatmapPromise;
let weatherPromise;
let riskPromise;
let forecastPromise;
let lastMission;

async function request(path, options) {
  const response = await fetch(`${API_BASE_URL}${path}`, {
    headers: { "Content-Type": "application/json" },
    ...options,
  });
  if (!response.ok) {
    throw new Error(`Backend request failed (${response.status}): ${path}`);
  }
  return response.json();
}

function formatDuration(hours) {
  const totalMinutes = Math.round(Number(hours || 0) * 60);
  return `${Math.floor(totalMinutes / 60)}h ${totalMinutes % 60}m`;
}

function mapRoute(route, id, index, threshold = 30, profileKey) {
  const colors = ["#ef4444", "#00d2ff", "#10b981"];
  const profiles = {
    fuel_efficient: { name: "Fastest Corridor", label: "Shortest transit / fuel efficient" },
    balanced: { name: "Moderate Corridor", label: "Balanced safety and ETA" },
    safest: { name: "Safest Corridor", label: "Lowest modeled risk" },
  };
  const profile = profiles[profileKey] || profiles.balanced;
  const riskPct = Number(route.overall_risk_score || 0);
  const breakdown = route.risk_breakdown || {};
  return {
    id,
    name: profile.name,
    label: profile.label,
    distanceNm: route.distance_nm,
    estimatedFuelMt: Number(route.fuel_consumption_mt || 0),
    etaFormatted: formatDuration(route.estimated_time_hours),
    riskPct,
    recommended: index === 1,
    confidencePct: Math.max(1, Math.round(100 - riskPct)),
    status: riskPct <= threshold ? "Within Operational Threshold" : "Above Operational Threshold",
    color: colors[index],
    dashArray: index === 0 ? "6,6" : null,
    summary: route.explanation,
    waypoints: route.waypoints || [],
    riskBreakdown: {
      seaIce: Number(breakdown.sea_ice ?? riskPct),
      iceberg: Number(breakdown.iceberg ?? riskPct),
      weather: Number(breakdown.weather ?? riskPct),
      navigation: Number(breakdown.navigation ?? riskPct),
    },
  };
}

function mapWaypoints(route) {
  return (route?.waypoints || []).map(([lat, lng], index, points) => ({
    id: index === points.length - 1 ? "DEST" : `WP-${String(index).padStart(2, "0")}`,
    name: index === points.length - 1 ? "Destination" : `WP-${String(index).padStart(2, "0")}`,
    lat,
    lng,
    etaOffset: "Calculated",
    seaIcePct: 0,
    icebergRiskPct: 0,
    weatherRiskPct: 0,
    visibilityKm: 0,
    localRiskPct: 0,
    wind: "Live telemetry",
    wave: "Live telemetry",
    note: "Generated by the backend risk-aware route engine.",
  }));
}

function mapIcebergs(icebergs = []) {
  return icebergs.map((berg) => ({
    ...berg,
    lng: berg.lon,
    size: "Tracked iceberg",
    lengthMeters: null,
    distanceToRouteNm: null,
    driftSpeedKn: null,
    driftDirection: "Model forecast",
    riskLevel: "Moderate",
    predictedPositions: (berg.trajectory || []).map(([lng, lat], index) => ({
      step: index === 0 ? "Current" : `+${index * 24}h`,
      lat,
      lng,
      time: index === 0 ? "00:00" : `${index * 24}:00`,
    })),
  }));
}

function mapIceZones(featureCollection, heatmap = {}) {
  const zones = (featureCollection?.features || []).map((feature, index) => {
    const coordinates = feature.geometry?.coordinates?.[0] || [];
    const center = coordinates.reduce(
      (sum, [lng, lat]) => [sum[0] + lat / coordinates.length, sum[1] + lng / coordinates.length],
      [0, 0],
    );
    return {
      id: `ice-zone-${index + 1}`,
      region: feature.properties?.name || "Sea-ice zone",
      concentrationPct: Math.round(Number(feature.properties?.risk || 0) * 100),
      trend: "Backend risk assessment",
      forecast48h: "Model dependent",
      riskRating: feature.properties?.type || "Unknown",
      wind: "See live telemetry",
      visibilityKm: 0,
      centerLat: center[0],
      centerLng: center[1],
      radiusMeters: 180000,
      color: index % 2 ? "#f59e0b" : "#dc2626",
    };
  });
  const points = (heatmap.points || []).map(([lat, lng, concentration], index) => ({
    id: `sat-ice-${index}`,
    region: "Satellite sea-ice concentration",
    concentrationPct: Math.round(Number(concentration || 0) * 100),
    trend: "Observed satellite raster",
    forecast48h: heatmap.observation_date || "Latest observation",
    riskRating: "Satellite observation",
    wind: "Not in raster",
    visibilityKm: 0,
    centerLat: lat,
    centerLng: lng,
    radiusMeters: 28000,
    color: seaIceColor(Number(concentration || 0)),
    isHeatPoint: true,
  }));
  return [...zones, ...points];
}

function seaIceColor(concentration) {
  if (concentration >= 0.75) return "#ef4444";
  if (concentration >= 0.5) return "#f59e0b";
  if (concentration >= 0.25) return "#22d3ee";
  return "#2563eb";
}

