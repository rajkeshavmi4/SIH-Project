/**
 * Fetch generated route alternatives (Route A, B, C).
 */
export async function getRoutes() {
  if (!routeBundlePromise) {
    routeBundlePromise = request("/api/routes/calculate", {
      method: "POST",
      body: JSON.stringify({
        start_lat: -53.1638,
        start_lon: -70.9171,
        dest_lat: -64.7742,
        dest_lon: -64.0531,
        departure_date: new Date().toISOString().slice(0, 10),
        vessel_type: "Polar Class 4",
      }),
    }).catch((error) => {
      routeBundlePromise = undefined;
      throw error;
    });
  }
  const data = await routeBundlePromise;
  return ["fuel_efficient", "balanced", "safest"].map((key, index) =>
    mapRoute(data.routes[key], `route-${String.fromCharCode(97 + index)}`, index, 30, key),
  );
}

/**
 * Fetch comprehensive risk analysis, donut breakdowns, and regional scores.
 */
export async function getRiskAnalysis() {
  if (!riskPromise) {
    riskPromise = request("/api/live/environmental-data?lat=-64.7742&lon=-64.0531").catch((error) => {
      riskPromise = undefined;
      throw error;
    });
  }
  const data = await riskPromise;
  const risk = data.risk_breakdown;
  const overallRiskPct = Math.round(Number(risk.total_risk || 0) * 100);
  return {
    overallRiskPct,
    status: overallRiskPct > 50 ? "High" : overallRiskPct > 25 ? "Moderate" : "Low",
    breakdown: {
      icePct: Math.round(Number(risk.sea_ice_risk || 0) * 100),
      icebergPct: Math.round(Number(risk.iceberg_risk || 0) * 100),
      weatherPct: Math.round(Number(risk.weather_risk || 0) * 100),
      routePct: overallRiskPct,
    },
    explanation: ["Risk values are calculated by the backend risk engine using live environmental inputs and trained ML services."],
    regionalRisk: [],
  };
}

