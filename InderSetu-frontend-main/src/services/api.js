/**
 * Fetch sea-ice concentration zones and regional polygon metadata.
 */
export async function getSeaIceData() {
  if (!environmentLayersPromise) {
    environmentLayersPromise = request("/api/environment/layers").catch((error) => {
      environmentLayersPromise = undefined;
      throw error;
    });
  }
  const data = await environmentLayersPromise;
  if (!seaIceHeatmapPromise) {
    seaIceHeatmapPromise = request("/api/sea-ice/heatmap?stride=6").catch((error) => {
      seaIceHeatmapPromise = undefined;
      throw error;
    });
  }
  const heatmap = await seaIceHeatmapPromise;
  return mapIceZones(data.ice_zones, heatmap);
}

