/**
 * Fetch 48-hour forecast timeline series.
 */
export async function getForecast48h() {
  if (!forecastPromise) {
    const date = new Date().toISOString().slice(0, 10);
    forecastPromise = request("/api/sea-ice/forecast", {
      method: "POST",
      body: JSON.stringify({ forecast_date: date }),
    }).catch((error) => {
      forecastPromise = undefined;
      throw error;
    });
  }
  const data = await forecastPromise;
  const seaIcePct = Math.round(data.mean * 100);
  return [0, 12, 24, 36, 48].map((offset) => ({
    step: `${offset}h`,
    seaIcePct,
    icebergDensity: 0,
    windKn: 0,
    waveM: 0,
    visibilityKm: 0,
    overallRiskPct: seaIcePct,
  }));
}

/**
 * Fetch Waypoints for a specific route ID.
 */
export async function getWaypoints(routeId = "route-b") {
  const routes = await getRoutes();
  const route = routes.find((item) => item.id === routeId) || routes[1];
  return mapWaypoints(route);
}

