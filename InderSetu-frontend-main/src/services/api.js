/**
 * Recalculate route alternatives based on modified mission inputs.
 */
export async function recalculateRoutes(inputs) {
  const departure = inputs.departureCoords || [-53.1638, -70.9171];
  const destination = inputs.destinationCoords || [-64.7742, -64.0531];
  const data = await request("/api/routes/calculate", {
    method: "POST",
    body: JSON.stringify({
      start_lat: departure[0], start_lon: departure[1],
      dest_lat: destination[0], dest_lon: destination[1],
      departure_date: inputs.date,
      vessel_type: inputs.vessel,
    }),
  });
  routeBundlePromise = Promise.resolve(data);
  return {
    success: true,
    message: "Routes recalculated by the backend risk-aware ML route engine.",
    timestamp: new Date().toISOString(),
    routes: ["fuel_efficient", "balanced", "safest"].map((key, index) => mapRoute(data.routes[key], `route-${String.fromCharCode(97 + index)}`, index, inputs.operationalRiskThresholdPct, key)),
  };
}

export async function rerouteEnRoute(inputs, selectedRouteId = "route-b") {
  const departure = inputs.departureCoords || [-53.1638, -70.9171];
  const destination = inputs.destinationCoords || [-64.7742, -64.0531];
  const profiles = {
    "route-a": "Fuel Efficient",
    "route-b": "Balanced",
    "route-c": "Safest",
  };
  const data = await request("/api/routes/reroute", {
    method: "POST",
    body: JSON.stringify({
      current_lat: -61.8,
      current_lon: -64.9,
      dest_lat: destination[0],
      dest_lon: destination[1],
      vessel_type: inputs.vessel,
      active_profile: profiles[selectedRouteId] || "Balanced",
    }),
  });
  return {
    ...data,
    route: {
      waypoints: data.full_voyage_waypoints || data.remaining_waypoints || [],
      distanceNm: data.remaining_distance_nm,
      etaFormatted: formatDuration(data.remaining_time_hours),
      estimatedFuelMt: Number(data.remaining_fuel_mt || 0),
      riskPct: data.remaining_risk_score,
    },
  };
}
